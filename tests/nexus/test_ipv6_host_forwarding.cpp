/*
 * Verifies which unicast messages `Ip6::HandleDatagram()` passes to the host
 * when the destination is not on the mesh, depending on the message origin.
 *
 * A message from the host (`kOriginHostUntrusted`) was already routed into
 * Thread by the host. Passing it back lets the host route it into Thread
 * again, so it would circulate between the host and Thread until its hop
 * limit expires. Such a message must not be passed back to the host, both
 * when Network Data has no route for it and when the route ends at this
 * Border Router. Messages from the Thread netif and messages generated by
 * the core (`kOriginHostTrusted`) are still passed to the host.
 *
 * Some checks emulate a host that routes every message it receives back
 * into Thread, and verify that such a message reaches the host only once.
 *
 * NAT64 messages from the host are still passed on: a message to the NAT64
 * prefix is translated to IPv4, and the IPv6 message translated from the
 * IPv4 reply reaches the requester, whether the requester is on the host,
 * on this Border Router or on another device in the mesh.
 */

#include <stdio.h>

#include "net/checksum.hpp"
#include "platform/nexus_core.hpp"
#include "platform/nexus_node.hpp"

namespace ot {
namespace Nexus {

static constexpr uint16_t kSourcePort      = 1234;
static constexpr uint16_t kDestinationPort = 12345;
static constexpr uint8_t  kHopLimit        = 64;
static constexpr uint32_t kDeliveryTime    = 2 * 1000;

static const char kHostAddress[]       = "fd70::1";
static const char kOmrAddress[]        = "fd80::1";
static const char kPeerOmrAddress[]    = "fd80::2";
static const char kOffMeshSrcAddress[] = "fd81::2";
static const char kOffMeshAddress[]    = "fd60::1";
static const char kNat64Address[]      = "fd64::c000:201";

struct HostRx
{
    // Test UDP messages passed to the host of a node.

    uint16_t       mCount;
    Ip6::Header    mHeader;
    Ip6::UdpHeader mUdpHeader;
    bool           mChecksumValid;
};

static Node             *sBr;
static HostRx            sBrHostRx;
static HostRx            sPeerHostRx;
static uint16_t          sIp4ToHostCount;
static Ip4::Header       sIp4Header;
static Ip6::UdpHeader    sIp4UdpHeader;
static bool              sHostRoutesToThread;
static OwnedPtr<Message> sHostToThreadMessage;

static bool IsTestMessage(const Ip6::Header &aHeader, const Ip6::UdpHeader &aUdpHeader)
{
    // Filters out messages that the stack passes to the host on its
    // own, such as multicast MLE messages.

    return !aHeader.GetDestination().IsMulticast() && (aHeader.GetNextHeader() == Ip6::kProtoUdp) &&
           (((aUdpHeader.GetSourcePort() == kSourcePort) && (aUdpHeader.GetDestinationPort() == kDestinationPort)) ||
            ((aUdpHeader.GetSourcePort() == kDestinationPort) && (aUdpHeader.GetDestinationPort() == kSourcePort)));
}

static void HandleIp6Receive(otMessage *aMessage, void *aContext)
{
    OwnedPtr<Message> messagePtr(AsCoreTypePtr(aMessage));
    HostRx           &hostRx = *static_cast<HostRx *>(aContext);
    Ip6::Header       header;
    Ip6::UdpHeader    udpHeader;
    Ip6::MessageInfo  messageInfo;

    SuccessOrQuit(messagePtr->Read(0, header));
    SuccessOrExit(messagePtr->Read(sizeof(header), udpHeader));
    VerifyOrExit(IsTestMessage(header, udpHeader));

    hostRx.mCount++;
    hostRx.mHeader    = header;
    hostRx.mUdpHeader = udpHeader;

    messageInfo.Clear();
    messageInfo.SetPeerAddr(header.GetSource());
    messageInfo.SetSockAddr(header.GetDestination());
    messagePtr->SetOffset(sizeof(header));
    hostRx.mChecksumValid = (Checksum::VerifyMessageChecksum(*messagePtr, messageInfo, Ip6::kProtoUdp) == kErrorNone);

    if (sHostRoutesToThread && (&hostRx == &sBrHostRx) && (header.GetHopLimit() > 1))
    {
        // Emulate a host that routes the message back into Thread. Like
        // a host writing to the Thread interface, it hands over a new
        // message holding the same bytes.

        VerifyOrQuit(sHostToThreadMessage == nullptr);
        sHostToThreadMessage.Reset(sBr->Get<MessagePool>().Allocate(Message::kTypeIp6));
        VerifyOrQuit(sHostToThreadMessage != nullptr);
        SuccessOrQuit(sHostToThreadMessage->AppendBytesFromMessage(*messagePtr, 0, messagePtr->GetLength()));
        header.SetHopLimit(header.GetHopLimit() - 1);
        sHostToThreadMessage->Write(0, header);
        sHostToThreadMessage->SetOrigin(Message::kOriginHostUntrusted);
    }

exit:
    return;
}

static void HandleIp4Receive(otMessage *aMessage, void *aContext)
{
    OT_UNUSED_VARIABLE(aContext);

    OwnedPtr<Message> messagePtr(AsCoreTypePtr(aMessage));

    sIp4ToHostCount++;
    SuccessOrQuit(messagePtr->Read(0, sIp4Header));
    SuccessOrQuit(messagePtr->Read(sIp4Header.GetHeaderLength(), sIp4UdpHeader));
}

static const char *OriginToString(Message::Origin aOrigin)
{
    const char *str = "unknown";

    switch (aOrigin)
    {
    case Message::kOriginThreadNetif:
        str = "thread-netif";
        break;
    case Message::kOriginHostTrusted:
        str = "host-trusted";
        break;
    case Message::kOriginHostUntrusted:
        str = "host-untrusted";
        break;
    }

    return str;
}

static OwnedPtr<Message> NewUdpMessage(Node &aNode, const char *aSource, const char *aDestination)
{
    OwnedPtr<Message> messagePtr(aNode.Get<MessagePool>().Allocate(Message::kTypeIp6));
    Ip6::Header       header;
    Ip6::UdpHeader    udpHeader;

    VerifyOrQuit(messagePtr != nullptr);

    header.Clear();
    header.InitVersionTrafficClassFlow();
    SuccessOrQuit(header.GetSource().FromString(aSource));
    SuccessOrQuit(header.GetDestination().FromString(aDestination));
    header.SetNextHeader(Ip6::kProtoUdp);
    header.SetPayloadLength(sizeof(udpHeader));
    header.SetHopLimit(kHopLimit);

    udpHeader.Clear();
    udpHeader.SetSourcePort(kSourcePort);
    udpHeader.SetDestinationPort(kDestinationPort);
    udpHeader.SetLength(sizeof(udpHeader));

    SuccessOrQuit(messagePtr->Append(header));
    SuccessOrQuit(messagePtr->Append(udpHeader));
    messagePtr->SetOffset(sizeof(header));
    Checksum::UpdateMessageChecksum(*messagePtr, header.GetSource(), header.GetDestination(), Ip6::kProtoUdp);
    messagePtr->SetOffset(0);

    return messagePtr;
}

static void SendOnBr(OwnedPtr<Message> aMessagePtr)
{
    // Sends a message on the Border Router, then sends any message
    // that the emulated host routes back into Thread.

    if (aMessagePtr->IsOriginThreadNetif())
    {
        SuccessOrQuit(sBr->Get<Ip6::Ip6>().HandleDatagram(aMessagePtr.PassOwnership()));
    }
    else
    {
        SuccessOrQuit(sBr->Get<Ip6::Ip6>().SendRaw(aMessagePtr.PassOwnership()));
    }

    while (sHostToThreadMessage != nullptr)
    {
        IgnoreError(sBr->Get<Ip6::Ip6>().SendRaw(sHostToThreadMessage.PassOwnership()));
    }
}

static void VerifyPassedToHost(const char     *aSource,
                               const char     *aDestination,
                               Message::Origin aOrigin,
                               uint16_t        aExpectedIp6Count,
                               uint16_t        aExpectedIp4Count = 0)
{
    // Sends a UDP message with origin `aOrigin` on the Border Router
    // and checks how many IPv6 and (NAT64-translated) IPv4 messages
    // are passed to the host.

    OwnedPtr<Message> messagePtr = NewUdpMessage(*sBr, aSource, aDestination);

    messagePtr->SetOrigin(aOrigin);

    sBrHostRx.mCount = 0;
    sIp4ToHostCount  = 0;

    SendOnBr(messagePtr.PassOwnership());

    Log("%s -> %s, origin %s%s: passed to host IPv6 %u (expected %u), IPv4 %u (expected %u)", aSource, aDestination,
        OriginToString(aOrigin), sHostRoutesToThread ? ", host routes back to Thread" : "", sBrHostRx.mCount,
        aExpectedIp6Count, sIp4ToHostCount, aExpectedIp4Count);

    VerifyOrQuit(sBrHostRx.mCount == aExpectedIp6Count);
    VerifyOrQuit(sIp4ToHostCount == aExpectedIp4Count);
}

static void VerifyPassedToHostOnce(const char *aSource, const char *aDestination, Message::Origin aOrigin)
{
    // Checks that a message from `aOrigin` reaches the host at most
    // once when the host routes it back into Thread. A message from
    // the host must not reach the host at all.

    sHostRoutesToThread = true;
    VerifyPassedToHost(aSource, aDestination, aOrigin, (aOrigin == Message::kOriginHostUntrusted) ? 0 : 1);
    sHostRoutesToThread = false;
}

static void SendNat64Reply(void)
{
    // Sends the reply of the IPv4 server to the last translated
    // request, as the host of the Border Router does with an IPv4
    // message written to the Thread interface.

    OwnedPtr<Message> messagePtr(AsCoreTypePtr(otIp4NewMessage(&sBr->GetInstance(), nullptr)));
    Ip4::Header       header;
    Ip6::UdpHeader    udpHeader;

    VerifyOrQuit(messagePtr != nullptr);

    header.Clear();
    header.InitVersionIhl();
    header.SetSource(sIp4Header.GetDestination());
    header.SetDestination(sIp4Header.GetSource());
    header.SetProtocol(Ip4::kProtoUdp);
    header.SetTtl(kHopLimit);
    header.SetTotalLength(sizeof(header) + sizeof(udpHeader));
    Checksum::UpdateIp4HeaderChecksum(header);

    udpHeader.Clear();
    udpHeader.SetSourcePort(sIp4UdpHeader.GetDestinationPort());
    udpHeader.SetDestinationPort(sIp4UdpHeader.GetSourcePort());
    udpHeader.SetLength(sizeof(udpHeader));

    SuccessOrQuit(messagePtr->Append(header));
    SuccessOrQuit(messagePtr->Append(udpHeader));
    messagePtr->SetOffset(sizeof(header));
    Checksum::UpdateMessageChecksum(*messagePtr, header.GetSource(), header.GetDestination(), Ip4::kProtoUdp);
    messagePtr->SetOffset(0);
    messagePtr->SetOrigin(Message::kOriginHostUntrusted);

    SuccessOrQuit(otNat64Send(&sBr->GetInstance(), messagePtr.Release()));
}

static void VerifyNat64RoundTrip(Core &aNexus, Node &aRequester, const char *aRequesterAddress, HostRx &aRequesterRx)
{
    // Sends a UDP request from `aRequesterAddress` to the NAT64
    // address, replies to the translated IPv4 request, and checks
    // that the requester receives the translated reply once.

    OwnedPtr<Message> requestPtr = NewUdpMessage(aRequester, aRequesterAddress, kNat64Address);
    Ip6::Address      requester;
    Ip6::Address      nat64Address;

    SuccessOrQuit(requester.FromString(aRequesterAddress));
    SuccessOrQuit(nat64Address.FromString(kNat64Address));

    sIp4ToHostCount = 0;

    if (&aRequester == sBr)
    {
        // A requester on the BR is a host application, unless the BR
        // owns the address. Either way the request comes from the host.

        requestPtr->SetOrigin(Message::kOriginHostUntrusted);
        SendOnBr(requestPtr.PassOwnership());
    }
    else
    {
        requestPtr->SetOrigin(Message::kOriginHostTrusted);
        SuccessOrQuit(aRequester.Get<Ip6::Ip6>().SendRaw(requestPtr.PassOwnership()));
        aNexus.AdvanceTime(kDeliveryTime);
    }

    VerifyOrQuit(sIp4ToHostCount == 1);

    aRequesterRx.mCount = 0;

    SendNat64Reply();
    aNexus.AdvanceTime(kDeliveryTime);

    Log("NAT64 round trip %s -> %s: requester received %u reply (expected 1)", aRequesterAddress, kNat64Address,
        aRequesterRx.mCount);

    VerifyOrQuit(aRequesterRx.mCount == 1);
    VerifyOrQuit(aRequesterRx.mHeader.GetSource() == nat64Address);
    VerifyOrQuit(aRequesterRx.mHeader.GetDestination() == requester);
    VerifyOrQuit(aRequesterRx.mUdpHeader.GetSourcePort() == kDestinationPort);
    VerifyOrQuit(aRequesterRx.mUdpHeader.GetDestinationPort() == kSourcePort);
    VerifyOrQuit(aRequesterRx.mChecksumValid);
}

static void AddUnicastAddress(Node &aNode, Ip6::Netif::UnicastAddress &aAddress, const char *aAddressString)
{
    aAddress.Clear();
    SuccessOrQuit(aAddress.GetAddress().FromString(aAddressString));
    aAddress.mPrefixLength = 64;
    aAddress.mPreferred    = true;
    aAddress.mValid        = true;
    aNode.Get<ThreadNetif>().AddUnicastAddress(aAddress);
}

static void AddBorderRouterPrefix(Node &aNode, const char *aPrefix, bool aOnMesh)
{
    NetworkData::OnMeshPrefixConfig prefixConfig;

    prefixConfig.Clear();
    SuccessOrQuit(prefixConfig.GetPrefix().FromString(aPrefix));
    prefixConfig.mOnMesh    = aOnMesh;
    prefixConfig.mPreferred = true;
    prefixConfig.mStable    = true;
    SuccessOrQuit(aNode.Get<NetworkData::Local>().AddOnMeshPrefix(prefixConfig));
}

static void VerifyRouteLookup(Node &aNode, const char *aSource, const char *aDestination, bool aEndsHere)
{
    Ip6::Address source;
    Ip6::Address destination;
    uint16_t     rloc16;

    SuccessOrQuit(source.FromString(aSource));
    SuccessOrQuit(destination.FromString(aDestination));

    if (aEndsHere)
    {
        SuccessOrQuit(aNode.Get<NetworkData::Leader>().RouteLookup(source, destination, rloc16));
        VerifyOrQuit(aNode.Get<Mle::Mle>().HasRloc16(rloc16));
    }
    else
    {
        VerifyOrQuit(aNode.Get<NetworkData::Leader>().RouteLookup(source, destination, rloc16) == kErrorNoRoute);
    }
}

void TestIp6HostForwarding(void)
{
    Core                             nexus;
    Node                            &br   = nexus.CreateNode();
    Node                            &peer = nexus.CreateNode();
    NetworkData::ExternalRouteConfig routeConfig;
    Ip6::Prefix                      nat64Prefix;
    Ip4::Cidr                        nat64Cidr;
    Ip6::Netif::UnicastAddress       omrAddress;
    Ip6::Netif::UnicastAddress       peerOmrAddress;

    sBr = &br;

    Log("---------------------------------------------------------------------------------------");
    Log("TestIp6HostForwarding");

    br.Form();
    nexus.AdvanceTime(13 * 1000);
    VerifyOrQuit(br.Get<Mle::Mle>().IsLeader());

    br.Get<Ip6::Ip6>().SetReceiveCallback(HandleIp6Receive, &sBrHostRx);
    br.Get<Ip6::Ip6>().SetNat64ReceiveIp4Callback(HandleIp4Receive, nullptr);

    SuccessOrQuit(nat64Prefix.FromString("fd64::/96"));
    SuccessOrQuit(nat64Cidr.FromString("192.168.123.0/24"));
    br.Get<Nat64::Translator>().SetNat64Prefix(nat64Prefix);
    SuccessOrQuit(br.Get<Nat64::Translator>().SetIp4Cidr(nat64Cidr));
    br.Get<Nat64::Translator>().SetEnabled(true);
    nexus.AdvanceTime(1);
    VerifyOrQuit(br.Get<Nat64::Translator>().GetState() == Nat64::kStateActive);

    // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    Log("No route in Network Data");

    VerifyRouteLookup(br, kHostAddress, kOffMeshAddress, /* aEndsHere */ false);
    VerifyRouteLookup(br, kNat64Address, kHostAddress, /* aEndsHere */ false);

    VerifyPassedToHost(kHostAddress, kOffMeshAddress, Message::kOriginThreadNetif, 1);
    VerifyPassedToHost(kHostAddress, kOffMeshAddress, Message::kOriginHostTrusted, 1);
    VerifyPassedToHost(kHostAddress, kOffMeshAddress, Message::kOriginHostUntrusted, 0);
    VerifyPassedToHost(kHostAddress, kNat64Address, Message::kOriginHostUntrusted, 0, 1);

    VerifyPassedToHostOnce(kHostAddress, kOffMeshAddress, Message::kOriginThreadNetif);
    VerifyPassedToHostOnce(kHostAddress, kOffMeshAddress, Message::kOriginHostUntrusted);

    VerifyNat64RoundTrip(nexus, br, kHostAddress, sBrHostRx);

    // A message from the host with the bytes of a translated reply is
    // not a translated message.
    VerifyPassedToHost(kNat64Address, kHostAddress, Message::kOriginHostUntrusted, 0);

    // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    Log("Network Data route ends at this Border Router");

    // `fd80::/64` is an on-mesh prefix. `fd81::/64` and `fd64::/64` are
    // not on-mesh, but a route lookup for a source within them uses the
    // `fc00::/7` route of this Border Router. `fd64::/64` contains the
    // NAT64 prefix, so this also applies to translated replies.

    AddBorderRouterPrefix(br, "fd80::/64", /* aOnMesh */ true);
    AddBorderRouterPrefix(br, "fd81::/64", /* aOnMesh */ false);
    AddBorderRouterPrefix(br, "fd64::/64", /* aOnMesh */ false);

    routeConfig.Clear();
    SuccessOrQuit(routeConfig.GetPrefix().FromString("fc00::/7"));
    routeConfig.mStable = true;
    SuccessOrQuit(br.Get<NetworkData::Local>().AddHasRoutePrefix(routeConfig));

    br.Get<NetworkData::Notifier>().HandleServerDataUpdated();
    AddUnicastAddress(br, omrAddress, kOmrAddress);
    nexus.AdvanceTime(10 * 1000);

    VerifyRouteLookup(br, kOmrAddress, kOffMeshAddress, /* aEndsHere */ true);
    VerifyRouteLookup(br, kOffMeshSrcAddress, kOffMeshAddress, /* aEndsHere */ true);
    VerifyRouteLookup(br, kNat64Address, kHostAddress, /* aEndsHere */ true);

    VerifyPassedToHost(kPeerOmrAddress, kOffMeshAddress, Message::kOriginThreadNetif, 1);
    VerifyPassedToHost(kOmrAddress, kOffMeshAddress, Message::kOriginHostTrusted, 1);
    VerifyPassedToHost(kOmrAddress, kOffMeshAddress, Message::kOriginHostUntrusted, 0);
    VerifyPassedToHost(kOmrAddress, kNat64Address, Message::kOriginHostUntrusted, 0, 1);

    VerifyPassedToHostOnce(kOffMeshSrcAddress, kOffMeshAddress, Message::kOriginThreadNetif);
    VerifyPassedToHostOnce(kOmrAddress, kOffMeshAddress, Message::kOriginHostUntrusted);

    VerifyNat64RoundTrip(nexus, br, kHostAddress, sBrHostRx);
    VerifyNat64RoundTrip(nexus, br, kOmrAddress, sBrHostRx);
    VerifyPassedToHost(kNat64Address, kHostAddress, Message::kOriginHostUntrusted, 0);

    // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    Log("NAT64 requester on another device in the mesh");

    peer.Join(br);
    nexus.AdvanceTime(30 * 1000);
    VerifyOrQuit(peer.Get<Mle::Mle>().IsAttached());

    peer.Get<Ip6::Ip6>().SetReceiveCallback(HandleIp6Receive, &sPeerHostRx);
    AddUnicastAddress(peer, peerOmrAddress, kPeerOmrAddress);
    nexus.AdvanceTime(10 * 1000);

    VerifyNat64RoundTrip(nexus, peer, kPeerOmrAddress, sPeerHostRx);

    peer.Get<ThreadNetif>().RemoveUnicastAddress(peerOmrAddress);
    br.Get<ThreadNetif>().RemoveUnicastAddress(omrAddress);
}

} // namespace Nexus
} // namespace ot

int main(void)
{
    ot::Nexus::TestIp6HostForwarding();
    printf("All tests passed\n");
    return 0;
}
